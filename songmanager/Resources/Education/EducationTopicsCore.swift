Organizations (who collects what)
They collect money; they do not distribute your music.

Publishing collectors (song)
- PROs: collect performance royalties (radio, TV, live, streaming performance portion). US: ASCAP, BMI, SESAC (invite), GMR (invite). Join one as a songwriter. International: PRS, SOCAN, SACEM, GEMA, APRA AMCOS, JASRAC; reciprocal deals mean you usually do not need multiple.
