- Live setlists: reporting shows to your PRO pays out performance royalties.

Master royalties (recording)
- Streaming: Spotify, Apple, YouTube Music. Collected by your distributor. Paid to the master owner.
- Sales/downloads: downloads and physical products. Paid to the master owner.
- Digital radio (US): Pandora or SiriusXM non-interactive streams. Collected by SoundExchange and split 50 percent master owner, 45 percent featured artist, 5 percent session players.
- Neighboring rights (international): radio, TV, and venue performance of the master abroad. Collected by orgs like PPL or Re:Sound and paid to performers and master owners.

YouTube and UGC
- Ads and Content ID pay both master and publishing. Distributor usually handles master claims; PRO or publisher handles publishing claims. Clear ownership to avoid leaks.

Other lanes
- Print: sheet music revenue to writers and publishers.
- Sampling or interpolation: clearance fee plus backend publishing and sometimes master share.
- Merch or brand tie-ins: revenue streams but not royalties.

Quick actions to avoid leaks
