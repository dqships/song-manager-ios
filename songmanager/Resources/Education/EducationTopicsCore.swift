- SoundExchange (US): collects non-interactive digital radio (Pandora, SiriusXM) and splits 50 percent master owner, 45 percent featured artist, 5 percent session players.
- Neighboring rights orgs (international): collect master performance abroad. Examples: PPL (UK), Re:Sound (Canada), SCPP or SPPF (France), GVL (Germany). Unregistered money just sits.

Sync licensing and YouTube
- Sync companies: libraries, boutique agencies, or direct supervisors place songs in film/TV/ads/games and handle clearance. Pays both publishing and master.
- YouTube monetization: Content ID via your distributor or an MCN; pays master and publishing separately when claims are correct.

Minimum no-leak stack (indie artist)
- One PRO (ASCAP or BMI).
- The MLC (direct registration).
- Publishing admin such as Songtrust.
- Distributor such as DistroKid or TuneCore.
- SoundExchange.
- Neighboring rights admin or targeted international signups.

