- Register with SoundExchange for master digital radio; add neighboring rights coverage if you have international spins.
- Store ISRC, UPC, contributors, and splits per song.
- Clear samples and features before release.

Mental model
- Song tree: performance, mechanical, sync, print.
- Recording tree: streaming, sales, digital radio, neighboring rights.
