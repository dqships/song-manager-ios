Ownership and Rights (Plain English)

Understanding who owns what is the difference between building wealth and building stress. This is a practical explanation, not legal advice.

The Two Assets in Music

1) The Song (Publishing)
This is the composition: lyrics, melody, and chords.
Owners: songwriters and publishers.

2) The Recording (Master)
This is the actual audio file you stream: the recorded performance and final mix or master.
Owners: usually the artist or label who funded the recording (depends on the deal).

Common Ownership Scenarios

Scenario A: You write and record everything yourself
- You own publishing (100 percent).
- You own the master (100 percent).

Scenario B: You co-write with another songwriter
- Publishing is split among writers and their publishers.
- Master ownership depends on who funded or controlled the recording.

Scenario C: Producer makes the beat and you write topline
- Publishing is often split (varies by agreement).
- Master ownership depends on the deal (fee versus points versus joint).

Scenario D: Label deal
- Label may own or control masters for a term.
- Publishing may stay with you unless you sign it away.

Rights You Should Know
- Master rights: who can distribute the recording, who can license it (sync), and who collects master royalties.
- Publishing rights: who can license the composition and who collects performance and mechanical royalties.

The Forever versus Temporary Mistake
- Dangerous language: "in perpetuity" (forever) or "exclusive" without a clear term and no clear reversion or exit.
- Rule: do not trade forever ownership for short-term convenience.

Simple Ownership Checklist Before Release
- Writers and splits agreed.
- Producer terms agreed.
- Master owner identified.
- Anyone who expects points or publishing documented.
- Any samples cleared or removed.
